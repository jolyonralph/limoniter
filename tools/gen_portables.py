#!/usr/bin/env python3
"""Builds data/charsets-portables.txt: the character sets of the Cambridge Z88 and the Amstrad NC100, NC150 and
NC200, in the same format as charsets.txt.
Usage: python3 -I tools/gen_portables.py <output>
Sources, none invented here:
- Cambridge Z88: the Z88 Developers' Notes, Appendix B (www.cl.cam.ac.uk/~jrh13/devnotes/all.html), which lists
  ASCII from &20 to &7E, &7F as delete, &A0 as the exact space and &A3 as the pound sign; the international OZ
  versions put their other letters at their ISO 8859-1 places (each version's font holding the ones its language
  needs), so &A0 to &FF are taken as ISO 8859-1, and &80 to &9F are left undefined.
- Amstrad NC: the ROM's characters as the NC Users' Site's ASCII Code Table Datasheet shows them
  (ncus.org.uk/dschars.htm, images/CHARS.gif): IBM code page 437, as Python's codec table has it, except &9B (o
  with stroke, where CP437 has the cent sign), &9D (O with stroke, where CP437 has the yen sign) and &FF (a return
  arrow, where CP437 has a no-break space).
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("gen_charsets", os.path.join(HERE, "gen_charsets.py"))
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)

Z88_SOURCE = "Z88 Developers' Notes, Appendix B (www.cl.cam.ac.uk/~jrh13/devnotes/all.html); ISO 8859-1 from " + gen.PY_SOURCE
NC_SOURCE = "NC Users' Site, ASCII Code Table Datasheet (ncus.org.uk/dschars.htm); CP437 from " + gen.PY_SOURCE


def z88():
    rows, back = gen.from_codec("latin-1")
    return {byte: row for byte, row in rows.items() if not 0x80 <= byte <= 0x9F}, back


def nc():
    rows, back = gen.from_codec("cp437")
    rows = dict(rows)
    rows[0x9B] = (0x00F8, "p", "")
    rows[0x9D] = (0x00D8, "p", "")
    rows[0xFF] = (0x21B5, "p", "")
    return rows, back


def main():
    output = sys.argv[1]
    out = open(output, "w", encoding="utf-8", newline="\n")
    out.write("# Generated by tools/gen_portables.py, in the same format as charsets.txt.\n")
    out.write("# Row: byte, Unicode (or -), kind (p printable, c control, s depends on display state), name. A byte with no row is undefined.\n\n")
    gen.write_charset(out, "z88", "Cambridge Z88", "Sinclair", Z88_SOURCE, gen.PY_VERSION,
                      "ASCII, with the pound sign at &A3 and the exact space at &A0; the international OZ versions' letters at their ISO 8859-1 places. &80 to &9F are undefined.",
                      [("Text", z88())])
    gen.write_charset(out, "amstrad-nc", "Amstrad NC100, NC150 and NC200", "Amstrad", NC_SOURCE, gen.PY_VERSION,
                      "The NC's ROM characters: IBM code page 437, with o and O with stroke at &9B and &9D and a return arrow at &FF.",
                      [("Text", nc())])
    out.close()
    print("2 sets")


if __name__ == "__main__":
    main()
